function inst(
  id: string,
  definitionId: string,
  assemblyId: string,
  name: string,
  positionMm: [number, number, number],
  explodeDirection: [number, number, number],
  explodeDistanceMm: number,
  rotationDeg: [number, number, number] = [0, 0, 0],
): PartInstance {
  return {
    id,
    definitionId,
    assemblyId,
    name,
    positionMm,
    explodeDirection,
    explodeDistanceMm,
    rotationDeg,
    visible: true,
  };
}
