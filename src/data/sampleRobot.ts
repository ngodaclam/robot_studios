import type { PartDefinition, PartInstance, Port, RobotProject } from '../domain/schema';

const power = (
  id: string,
  direction: 'in' | 'out',
  voltageV?: [number, number],
  currentA?: number,
  channels?: number,
): Port => ({
  id,
  name: id === 'supply' ? 'Nguồn vào' : 'Nguồn ra',
  kind: 'power',
  direction,
  required: direction === 'in',
  voltageV,
  currentA,
  channels,
});
const logic = (id: string, direction: 'in' | 'out', voltageV?: [number, number]): Port => ({
  id,
  name: 'Tín hiệu điều khiển',
  kind: 'logic',
  direction,
  required: direction === 'in',
  voltageV,
});
const mechanical = (id: string, direction: 'in' | 'out', diameterMm: number): Port => ({
  id,
  name: direction === 'in' ? 'Lỗ trục' : 'Trục ra',
  kind: 'mechanical',
  direction,
  required: direction === 'in',
  diameterMm,
});
function def(
  id: string,
  name: string,
  category: string,
  geometry: PartDefinition['geometry'],
  dimensionsMm: [number, number, number],
  massG: number,
  priceVnd: number | null,
  color: string,
  specs: Record<string, string> = {},
  ports: Port[] = [],
): PartDefinition {
  return {
    id,
    name,
    category,
    geometry,
    dimensionsMm,
    massG,
    priceVnd,
    color,
    specs,
    ports,
    sku: `DEMO-${id.toUpperCase()}`,
    manufacturer: 'Robot Studio · minh họa',
    description: `${name} trong thiết kế robot di chuyển trong nhà. Kích thước và thông số giả định để khám phá phương án lắp ráp.`,
    source:
      'Danh mục minh họa do Robot Studio tự đặt. Chưa đối chiếu datasheet hoặc nhà cung cấp; không dùng để đặt mua.',
    verification: 'illustrative',
  };
}
